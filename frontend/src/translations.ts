export function translateMessage(message: string, locale: "ar" | "en"): string {
  if (locale === "ar") return message;
  if (messages[message]) return messages[message];
  let translated = message;
  for (const [ar, en] of Object.entries(messages).sort((a, b) => b[0].length - a[0].length)) {
    translated = translated.replaceAll(ar, en);
  }
  return translated.replace(/حاول بعد (\d+) ثانية\./g, "Try again in $1 seconds.");
}

